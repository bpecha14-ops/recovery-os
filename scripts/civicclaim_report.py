# ---------------------------------------------------------------- helpers
def nb(text):
    """Bind em dash to the previous word so a line never starts with '—'."""
    return text.replace(" — ", "\u00a0— ")


def P(text, style=body):
    return Paragraph(nb(text), style)


def add_heading(text, style, level=0):
    key = "h_%s" % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def chapter(story, num, title, first_flowables):
    """H1 with accent rule; keeps heading + rule + first flowable together."""
    head = add_heading("%d. %s" % (num, title), h1, level=0)
    rule = HRFlowable(width="100%", color=ACCENT, thickness=1.2,
                      spaceBefore=2, spaceAfter=10)
    story.append(CondPageBreak(H1_ORPHAN))
    story.append(KeepTogether([head, rule, first_flowables[0]]))
    story.extend(first_flowables[1:])


def make_table(header_row, rows, ratios, align_cols_center=None):
    """All cells wrapped in Paragraph; widths proportional to AVAIL_W."""
    align_cols_center = align_cols_center or []
    data = [[Paragraph("<b>%s</b>" % h, cell_hc if i in align_cols_center else cell_h)
             for i, h in enumerate(header_row)]]
    for r in rows:
        data.append([Paragraph(nb(str(v)), cell_c if i in align_cols_center else cell)
                     for i, v in enumerate(r)])
    widths = [r * AVAIL_W for r in ratios]
    assert sum(widths) <= AVAIL_W + 0.5, "table overflow"
    t = Table(data, colWidths=widths, hAlign="CENTER", repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i),
                      TABLE_ROW_ODD if i % 2 == 1 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    return t


def table_block(story, title_text, tbl, cap):
    story.append(Spacer(1, 10))
    if len(tbl._cellvalues) <= 15:
        story.append(KeepTogether([P("<b>%s</b>" % title_text, h2), tbl]))
    else:
        story.append(P("<b>%s</b>" % title_text, h2))
        story.append(tbl)
    story.append(Spacer(1, 6))
    story.append(P(cap, caption))
    story.append(Spacer(1, 10))


def stat_row(story, stats):
    """Row of stat callouts: [(value, label), ...]"""
    n = len(stats)
    gap = 8
    w = (AVAIL_W - gap * (n - 1)) / n
    cells_v, widths = [], []
    for i, (v, l) in enumerate(stats):
        box = Table([[Paragraph("<b>%s</b>" % v, stat_big)],
                     [Paragraph(l, stat_lbl)]], colWidths=[w])
        box.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
            ("BOX", (0, 0), (-1, -1), 0.8, ACCENT),
            ("TOPPADDING", (0, 0), (-1, 0), 9),
            ("BOTTOMPADDING", (0, 1), (-1, 1), 8),
            ("TOPPADDING", (0, 1), (-1, 1), 2),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ]))
        cells_v.append(box)
        widths.append(w)
        if i < n - 1:
            cells_v.append("")
            widths.append(gap)
    wrap = Table([cells_v], colWidths=widths, hAlign="CENTER")
    wrap.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    story.append(Spacer(1, 6))
    story.append(KeepTogether([wrap]))
    story.append(Spacer(1, 12))


